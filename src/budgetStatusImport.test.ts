// 예산현황 · 계약현황 양식(v3) 가져오기 검산 – 지금 동작을 고정해요(정리 2차 2026-10-26).
// 보기: '24.7. 호우 복구 – 국50:도20:시30(집행·예산 연동 결정 로그 10-25), 지급액은 오래된 예산(이월분)부터.
import { describe, expect, test } from "vitest";
import type { GridSheet } from "./budgetExcel";
import { allocate, parseV3, planV3 } from "./budgetStatusImport";

const contracts: GridSheet = {
  name: "계약",
  rows: [
    ["24.7. 호우 복구"],
    ["번호", "계약종류", "계약명", "합계금액", "2024년 예산", "", "", "", "2025년 예산", "", "", "", "지급액(원)", "", "", "완료여부"],
    ["", "", "", "원인행위 합계", "", "국비", "도비", "시비", "", "국비", "도비", "시비", "2024", "2025", "2026", ""],
    ["1", "공사", "호우 피해 복구공사", "100,000,000", "", "50,000,000", "20,000,000", "30,000,000", "", "", "", "", "40,000,000", "60,000,000", "", "완료"],
    ["2", "용역", "실시설계용역", "10,000,000", "", "", "", "", "", "5,000,000", "2,000,000", "3,000,000", "", "4,000,000", "6,000,000", ""],
    ["", "", "", "", "", "", "", "", "", "", "", "", "", "", "", ""],
  ],
};
const ledger: GridSheet = {
  name: "연도·재원",
  rows: [
    ["사업명", "24.7. 호우 복구"],
    ["사업기간", "2024~2026"],
    ["연도", "재원", "본예산", "1추", "2추", "3추", "4추", "다음연도 이월(명시)", "다음연도 이월(사고)", "불용액"],
    ["2024", "국비", "50,000,000", "", "", "", "", "30,000,000", "", ""],
    ["", "도비", "20,000,000", "", "", "", "", "12,000,000", "", ""],
    ["", "시비", "30,000,000", "", "", "", "", "18,000,000", "", ""],
    ["", "소계", "100,000,000"],
    ["2025", "국비", "5,000,000", "", "", "", "", "3,000,000", "", ""],
    ["", "도비", "2,000,000", "", "", "", "", "1,200,000", "", ""],
    ["", "시비", "3,000,000", "", "", "", "", "1,800,000", "", "10"],
  ],
};

describe("parseV3", () => {
  test("두 시트를 읽어요", () => {
    const p = parseV3([contracts, ledger]);
    if (typeof p === "string") throw new Error(p);
    expect([p.name, p.from, p.to, p.sources]).toEqual(["24.7. 호우 복구", 2024, 2026, ["국비", "도비", "시비"]]);
    expect(p.contracts).toEqual([
      { kind: "공사", name: "호우 피해 복구공사", done: true, pots: { 2024: { 국비: 50_000_000, 도비: 20_000_000, 시비: 30_000_000 } }, pays: { 2024: 40_000_000, 2025: 60_000_000 } },
      { kind: "용역", name: "실시설계용역", done: false, pots: { 2025: { 국비: 5_000_000, 도비: 2_000_000, 시비: 3_000_000 } }, pays: { 2025: 4_000_000, 2026: 6_000_000 } },
    ]);
    expect(p.manual["2024:국비"]).toEqual({ cur: 50_000_000, nm: 30_000_000 });
    expect(p.manual["2025:시비"]).toEqual({ cur: 3_000_000, nm: 1_800_000, un: 10 });
    expect(p.manual["2024:소계"]).toBeUndefined();
  });
  test("양식이 아니면 까닭 글", () => {
    expect(parseV3([ledger])).toBe("계약현황 양식([계약]·[연도·재원] 시트)이 아니에요");
  });
});

describe("allocate – 오래된 예산부터, 재원은 금액 비율", () => {
  test("국50:도20:시30", () => {
    const p = parseV3([contracts, ledger]);
    if (typeof p === "string") throw new Error(p);
    expect(allocate(p.contracts[0], p.sources)).toEqual([
      { payYear: 2024, potYear: 2024, funds: { 국비: 20_000_000, 도비: 8_000_000, 시비: 12_000_000 }, amount: 40_000_000 },
      { payYear: 2025, potYear: 2024, funds: { 국비: 30_000_000, 도비: 12_000_000, 시비: 18_000_000 }, amount: 60_000_000 },
    ]);
  });
  test("끝자리는 마지막 재원이 맞춰요(십원 반올림)", () => {
    const a = allocate({ kind: "공사", name: "x", done: false, pots: { 2024: { 국비: 50, 도비: 20, 시비: 30 } }, pays: { 2024: 1_234_567 } }, ["국비", "도비", "시비"]);
    expect(a).toMatchInlineSnapshot(`""x" – 2024년 지급 1,234,467원이 원인행위(예산 배정)보다 많아요"`);
  });
  test("원인행위보다 많이 지급하면 까닭 글", () => {
    expect(allocate({ kind: "공사", name: "x", done: false, pots: { 2024: { 시비: 100 } }, pays: { 2024: 150 } }, ["시비"])).toBe('"x" – 2024년 지급 50원이 원인행위(예산 배정)보다 많아요');
  });
  test("이월은 2회까지", () => {
    expect(allocate({ kind: "공사", name: "x", done: false, pots: { 2024: { 시비: 100 } }, pays: { 2027: 100 } }, ["시비"])).toBe('"x" – 2027년 지급이 2024년 예산보다 3년 뒤예요(이월은 2회까지)');
  });
});

