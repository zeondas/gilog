import { describe, expect, test } from "vitest";
import { finalizePhone, formatPhone, isAutoShape } from "./phone";

describe("finalizePhone – 칸을 떠날 때", () => {
  test.each([
    ["1111", "1111"], // 네 자리 이하는 내선번호(10-25 19:49)
    ["94012", "94012"], // 모자란 자리 수는 숫자만(10-28)
    ["9401234", "940-1234"],
    ["94001234", "9400-1234"],
    ["01012345678", "010-1234-5678"],
    ["0101234567", "010-123-4567"],
    ["0319401234", "031-940-1234"],
    ["03112345678", "031-1234-5678"],
    ["021234567", "02-123-4567"],
    ["0212345678", "02-1234-5678"],
    ["15881234", "1588-1234"],
    ["05051234567", "0505-123-4567"],
    ["050512345678", "0505-1234-5678"],
    ["010-1234-5678", "010-1234-5678"],
    // 하이픈 자리가 틀려도 숫자·하이픈만이면 규칙대로 다시(10-28 사용자 1안)
    ["010-72805715", "010-7280-5715"],
    ["0107280-5715", "010-7280-5715"],
    ["0107-280-5715", "010-7280-5715"],
    ["0319400-1234", "031-9400-1234"],
    ["1588-1-234", "1588-1234"],
    ["11-11", "1111"],
    // 자리 수가 모자라면 숫자만(10-28 사용자 1안)
    ["12345", "12345"],
    ["123456", "123456"],
    ["1588123", "1588123"],
    ["0101234", "0101234"],
    ["010-123-4", "0101234"],
    ["02123456", "02123456"],
    ["031) 940-1234", "031) 940-1234"], // 다른 글자가 섞인 모양은 그대로
    ["내선 1111", "내선 1111"],
    ["", ""],
  ])("%s → %s", (v, want) => expect(finalizePhone(v)).toBe(want));
});

describe("formatPhone – 치는 중", () => {
  test.each([
    ["010", "010"],
    ["0101", "010-1"],
    ["01012345", "010-1234-5"],
    ["0319", "031-9"],
    ["0319401", "031-940-1"],
    ["123456789", "123456789"], // 규칙에 안 맞는 자리 수는 그대로
  ])("%s → %s", (v, want) => expect(formatPhone(v)).toBe(want));
});

test("isAutoShape – 자동으로 붙인 모양인지", () => {
  expect(isAutoShape("010-1234-5678")).toBe(true);
  expect(isAutoShape("01012345678")).toBe(true);
  expect(isAutoShape("0101-234-5678")).toBe(true);
  expect(isAutoShape("031) 940-1234")).toBe(false);
  expect(isAutoShape("내선 1111")).toBe(false);
});
