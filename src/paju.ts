/** 위치 칸 후보 하나: 법정리·동 이름과 그 읍면동 */
export type Place = { name: string; emd: string };

/** 법정리·동 → 읍면동. 동 지역에서 여러 행정동에 걸친 법정동은 행정동마다 하나씩이에요(동패동 → 4개). */
export const PLACES: Place[] = TABLE.flatMap(([emd, list]) => list.split(",").map((name) => ({ name, emd })));

/** 이 법정리·동이 속한 읍면동들 */
export const emdsOf = (name: string) => PLACES.filter((p) => p.name === name).map((p) => p.emd);

/** 끝의 리·동·읍·면을 뺀 이름 ("봉일천리" → "봉일천") – 초성을 칠 때 끝 글자는 보통 안 쳐요 */
const stem = (s: string) => (s.length > 2 && /[리동읍면]$/.test(s) ? s.slice(0, -1) : s);

/**
 * 친 글자(초성·글자 섞어도 돼요)로 시작하는 이름들. 초성이 꼭 맞는 것이 앞에 와요.
 * 예: "ㅂㅇㅊ" → 봉일천리, "ㅁㅈ" → 마장리·마정리·마지리·문지리, "마ㅈ" → 마장리·마정리·마지리
 */
export function findNames<T>(q: string, items: T[], nameOf: (x: T) => string): T[] {
  const s = splitJamo(q.trim());
  if (!s) return [];
  const hit = items.filter((x) => koIndex(nameOf(x), s) === 0);
  const exact = (x: T) => {
    const n = nameOf(x);
    if (n === s) return 0;
    if (isChosung(s) && (initials(stem(n)) === s || initials(n) === s)) return 1;
    return 2;
  };
  return hit.sort((a, b) => exact(a) - exact(b));
}

/** 위치 칸의 맨 앞 낱말(리·동 자리)과 나머지(지번 등) */
export function splitPlace(v: string): { head: string; rest: string } {
  const m = /^(\S*)(.*)$/s.exec(v) ?? ["", "", ""];
  return { head: m[1], rest: m[2] };
}
